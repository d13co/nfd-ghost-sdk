// Writes src/generated/reader.ts from the NfdQueryReader's ARC-56 spec: the compiled programs and the method
// signatures, which is all the SDK needs (it never deploys the reader, so no TEAL source or client).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const spec = JSON.parse(
  readFileSync(join(root, "../contracts/smart_contracts/artifacts/nfd_query_reader/NfdQueryReader.arc56.json"), "utf8"),
)
if (!spec.byteCode?.approval) throw new Error("copy-reader: the ARC-56 spec has no byteCode; build with --output-bytecode")

const signature = (m) => `${m.name}(${m.args.map((a) => a.type).join(",")})${m.returns.type}`
const out = `// Generated by scripts/copy-reader.mjs from NfdQueryReader.arc56.json (${spec.compilerInfo?.compiler ?? "puya"} ${
  spec.compilerInfo ? Object.values(spec.compilerInfo.compilerVersion).join(".") : ""
}). Do not edit.

/** The reader's approval program, base64. */
export const READER_APPROVAL_B64 = ${JSON.stringify(spec.byteCode.approval)}
/** The reader's clear state program, base64. */
export const READER_CLEAR_B64 = ${JSON.stringify(spec.byteCode.clear)}
/** The reader's ABI methods. */
export const READER_METHODS = {
${spec.methods.map((m) => `  ${m.name}: ${JSON.stringify(signature(m))},`).join("\n")}
} as const
`
mkdirSync(join(root, "src/generated"), { recursive: true })
writeFileSync(join(root, "src/generated/reader.ts"), out)
console.log(`copy-reader: wrote src/generated/reader.ts (${Buffer.from(spec.byteCode.approval, "base64").length} byte program)`)
